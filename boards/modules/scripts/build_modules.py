"""Generate independent Ergogen sources for two 75.2 mm square module studies.
Run: python3 scripts/build_modules.py; npx ergogen ergogen/module2.yaml -o output/module2 -f ergogen/footprints
These are placement/electrical review drafts, not production-ready PCB layouts.
"""
from pathlib import Path
import copy
import yaml

ROOT = Path(__file__).resolve().parents[1]
base = yaml.safe_load((ROOT/'ergogen/config.yaml').read_text())

def zone(x, y, tags):
    return {'anchor': {'shift': [x, y]}, 'key': {'tags': tags}}

def make(number):
    c = copy.deepcopy(base)
    c['meta']['name'] = f'Braille module {number} placement study'
    c['units']['battery_w'] = 12 if number == 2 else 50
    c['units']['battery_h'] = 30 if number == 2 else 50
    c['units']['battery_t'] = 3
    c['points']['zones'].pop('keys')
    z = c['points']['zones']
    if number == 2:
        # Preserve the four original top-row switch centers and orientations.
        for i in range(4):
            z[f'key_top_{i+1}'] = zone(f'100 + {i} pitch_x', '-100 + row_step', ['switch', 'rot_cw' if i in (0,3) else 'rot_ccw'])
        z['key_bottom_left'] = zone('100', '-100 - row_step - 4', ['switch', 'rot_cw'])
        z['key_bottom_right'] = zone('100 + 3 pitch_x', '-100 - row_step - 4', ['switch', 'rot_ccw'])
        # Central space is limited: keep battery on an insulated raised shelf.
        z['controller']['anchor']['shift'] = ['100 + 0.65 pitch_x', '-100 - 1']
        z['display']['anchor']['shift'] = ['100 + 2.25 pitch_x', '-100 - 1']
        z['battery']['anchor']['shift'] = ['100 + 1.5 pitch_x', '-100 - 2']
        z['power']['anchor.shift'] = ['100 + 1.25 pitch_x', '-100 - 0.5 board_h + 3.6']
        # Side-actuated reset has pads 2.625 mm below its anchor. Inset it
        # so all four copper pads remain inside the board-edge clearance.
        z['reset']['anchor.shift'] = ['100 + 2 pitch_x', '-100 - 0.5 board_h + 4.8']
        z['jst']['anchor.shift'] = ['100 + 1.5 pitch_x', '-100 - 0.5 board_h + 18.6']
    else:
        for i in range(4):
            z[f'key_bottom_{i+1}'] = zone(f'100 + {i} pitch_x', '-100 - row_step - 4', ['switch', 'rot_cw' if i in (0,3) else 'rot_ccw'])
        z['trackpad'] = zone('100 + 1.5 pitch_x', '-100 + 9', ['trackpad'])
        z['controller']['anchor']['shift'] = ['100 + 0.55 pitch_x', '-100 + 11']
        z['display']['anchor']['shift'] = ['100 + 2.5 pitch_x', '-100 + 11']
        z['battery']['anchor']['shift'] = ['100 + 1.5 pitch_x', '-100 + 5']
        z['power']['anchor.shift'] = ['100 + 0.4 pitch_x', '-100 - 0.5 board_h + 3.6']
        z['reset']['anchor.shift'] = ['100 + 2.6 pitch_x', '-100 - 0.5 board_h + 4.8']
        z['jst']['anchor.shift'] = ['100 + 1.5 pitch_x', '-100 + 0.5 board_h - 5']
    # Reuse the board perimeter/mount hole pattern verbatim. Swap keycap drawing.
    c['outlines']['nominal_keycaps'] = [
        {'what':'rectangle', 'where': 'switch', 'size': ['cap_w', 'cap_outer_h' if number == 2 else 'cap_mid_h'], 'corner': 1.2}]
    if number == 2:
        c['outlines']['nominal_keycaps'][0]['where'] = '/^key_top_/'
        c['outlines']['nominal_keycaps'].append({'what':'rectangle', 'where':'/^key_bottom_/', 'size':['cap_w','cap_mid_h'], 'corner':1.2})
    else:
        c['outlines']['trackpad_envelope'] = [{'what':'rectangle','where':'trackpad','size':[43,43], 'corner':1}]
    fp = c['pcbs'].pop('braille_placement')
    c['pcbs'][f'module{number}_placement'] = fp
    if number == 3:
        fp['outlines']['touch_surface'] = {'outline':'trackpad_envelope','layer':'Dwgs.User'}
    else:
        fp['outlines']['cell']['layer'] = 'F.Fab'
    for name in ('controller','display','reset','power','battery_connector'):
        fp['footprints'][name]['params']['side'] = 'F' if name != 'battery_connector' or number == 2 else 'B'
    fp['footprints']['mounts']['params']['side'] = 'B'
    pins = fp['footprints']['controller']['params']
    for pin in list(pins):
        if pin.startswith('P') and pin[1:].isdigit():
            del pins[pin]
    key_names = [f'key_top_{i+1}' for i in range(4)] + ['key_bottom_left','key_bottom_right'] if number == 2 else [f'key_bottom_{i+1}' for i in range(4)]
    for pin, name in zip(['P4','P5','P6','P7','P8','P9'], key_names):
        pins[pin] = name
    if number == 3:
        # Controller pin allocation for an external 3.3V TPS43 I2C breakout.
        pins.update(P14='TP_SDA', P15='TP_SCL', P16='TP_RDY', P18='TP_RST')
        fp['footprints']['trackpad_interface'] = {'what':'local/tps43_interface', 'where':'trackpad',
            'params':{'side':'F','VCC':'3V3','GND':'GND','SDA':'TP_SDA','SCL':'TP_SCL','RDY':'TP_RDY','RST':'TP_RST'}}
    (ROOT/'ergogen'/f'module{number}.yaml').write_text('# Generated by scripts/build_modules.py; module placement study.\n'+yaml.safe_dump(c, sort_keys=False))

for number in (2,3): make(number)
